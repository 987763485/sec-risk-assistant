-- 000003_user_token_epoch —— 访问令牌生效下界
--
-- 背景：访问令牌是无状态 JWT，签发后服务端不再持有它的任何记录。
-- 因此「用户点了登出」这件事对已经签发出去的令牌毫无影响——
-- 旧令牌仍能用满剩余的 15 分钟有效期。
--
-- 在单人使用的场景下这还能忍，但政企内部普遍存在共用终端：
-- 甲登出后离开工位，乙在 15 分钟内按一下浏览器的后退键就能继续以甲的身份操作。
--
-- 解决方式：在账号上记录一个「令牌生效下界」。认证中间件在加载账号时
-- 顺带比对该时间点，早于它的令牌一律拒绝。
--
-- 为什么不做成逐令牌吊销表：那需要为每个签发的 JWT 落一行记录，
-- 既失去 JWT 无状态的意义，又要为过期数据维护清理逻辑。
-- 一个时间戳即可覆盖「让此前所有令牌失效」这一全部实际需求，
-- 且因为认证中间件本来就会查一次 users 表，零额外查询成本。

ALTER TABLE `users`
  ADD COLUMN `token_not_before` DATETIME(3) NULL DEFAULT NULL
  COMMENT '访问令牌生效下界：签发时间早于此值的令牌一律拒绝'
  AFTER `password_changed_at`;
